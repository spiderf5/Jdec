import java.io.BufferedReader;
import java.io.PrintWriter;
import java.lang.reflect.Method;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Paths;

/**
 * myau.s3 name-mapping table brute-forcer.
 *
 * s3 is ZKM's runtime reflection-name deobfuscation library: the jar's
 * real class/method/field names live in an encrypted table (11 blobs,
 * SHA-512 keyed, XOR masked). Instead of reimplementing the crypto, we
 * load s3 itself (its <clinit> builds the map from the blobs and works
 * in a bare JVM) and invoke its private lookup b(String) for every
 * candidate key generated by gen_namekeys.py. Zero semantic drift.
 *
 * args: <keys.tsv> <out.tsv>   key lines: KIND \t KEY (\b escaped on output)
 */
public class DumpTable {
    public static void main(String[] args) throws Exception {
        Class<?> s3 = Class.forName("myau.s3", true, DumpTable.class.getClassLoader());
        Method b = s3.getDeclaredMethod("b", String.class);
        b.setAccessible(true);
        long n = 0, hit = 0;
        try (BufferedReader r = Files.newBufferedReader(Paths.get(args[0]), StandardCharsets.UTF_8);
             PrintWriter out = new PrintWriter(Files.newBufferedWriter(Paths.get(args[1]), StandardCharsets.UTF_8), true)) {
            String line;
            while ((line = r.readLine()) != null) {
                int tab = line.indexOf('\t');
                if (tab < 0) continue;
                String typ = line.substring(0, tab);
                String key = line.substring(tab + 1);
                n++;
                String res;
                try {
                    res = (String) b.invoke(null, key);
                } catch (Throwable t) {
                    res = null;
                }
                if (res != null && !res.isEmpty()) {
                    hit++;
                    out.println(typ + "\t" + key.replace("\b", "\\b") + "\t" + res);
                }
            }
            out.println("# hits=" + hit + "/" + n);
        }
        System.out.println("DumpTable done: " + hit + " hits / " + n + " keys");
    }
}
